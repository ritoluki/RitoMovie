// npm run build && node --test tests/notifications.integration.cjs
// All accounts and writes belong to a disposable local MongoDB database.
const { test, mock } = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const mongoose = require('mongoose');
process.env.JWT_SECRET = 'notifications-integration-test-only';
const interval = global.setInterval;
mock.method(global, 'setInterval', (...args) => interval(...args).unref());
const originalError = console.error;
mock.method(console, 'error', (...args) => {
  if (!args[1]?.isOperational) originalError(...args);
});
const User = require('../dist/models/User').default;
const Comment = require('../dist/models/Comment').default;
const Notification = require('../dist/models/Notification').default;
const Report = require('../dist/models/Report').default;
const { notificationEvents } = require('../dist/services/notificationEvents');
const { createNotification } = require('../dist/services/notificationService');
const {
  closeNotificationStreams,
} = require('../dist/controllers/notificationController');
const {
  closeAdminStreams,
} = require('../dist/controllers/admin/adminEventController');

test(
  'notifications persist, are private, synchronize read state and are generated by replies, restrictions and report outcomes',
  { timeout: 60000 },
  async (t) => {
    const dbName = `ritomovie_notifications_test_${process.pid}_${Date.now()}`;
    const aborters = [];
    let server;
    t.after(async () => {
      aborters.forEach((controller) => controller.abort());
      closeNotificationStreams();
      closeAdminStreams();
      if (server) {
        server.closeAllConnections();
        await new Promise((resolve) => server.close(resolve));
      }
      if (
        mongoose.connection.name === dbName &&
        /^ritomovie_notifications_test_\d+_\d+$/.test(dbName)
      )
        await mongoose.connection.dropDatabase();
      await mongoose.disconnect();
      mock.restoreAll();
    });
    await mongoose.connect('mongodb://127.0.0.1:27017', {
      dbName,
      serverSelectionTimeoutMS: 5000,
    });
    await Promise.all([Notification.init(), Report.init()]);
    const [alice, bob, staff] = await Promise.all(
      ['alice', 'bob', 'staff'].map((name) =>
        User.create({
          name,
          email: `${name}@example.com`,
          password: 'Test-Only-Password1!',
          role: name === 'staff' ? 'super_admin' : 'user',
        })
      )
    );
    const app = express();
    app.use(express.json());
    app.use(
      '/api/notifications',
      require('../dist/routes/notifications').default
    );
    app.use('/api/comments', require('../dist/routes/comments').default);
    app.use('/api/reports', require('../dist/routes/reports').default);
    app.use('/api/admin', require('../dist/routes/admin').default);
    app.use(require('../dist/middleware/errorHandler').default);
    server = await new Promise((resolve) => {
      const instance = app.listen(0, '127.0.0.1', () => resolve(instance));
    });
    const origin = `http://127.0.0.1:${server.address().port}`;
    const request = async (path, user = alice, method = 'GET', body) => {
      const response = await fetch(origin + path, {
        method,
        headers: {
          'Content-Type': 'application/json',
          ...(user
            ? { Authorization: `Bearer ${user.getSignedJwtToken()}` }
            : {}),
        },
        ...(body === undefined ? {} : { body: JSON.stringify(body) }),
      });
      return { status: response.status, body: await response.json() };
    };
    assert.equal((await request('/api/notifications', null)).status, 401);
    const root = await Comment.create({
      user: alice._id,
      movie: 42,
      text: 'Original parent comment',
      sourcePath: '/movie/42?phimSlug=test-season',
    });
    const posted = await request('/api/comments', bob, 'POST', {
      movie: 42,
      text: 'A reply to the original comment',
      parentComment: root.id,
      sourcePath: '/movie/42?phimSlug=test-season',
    });
    assert.equal(posted.status, 201);
    let replyNotice = await Notification.findOne({
      recipient: alice._id,
      type: 'COMMENT_REPLY',
    });
    assert.ok(replyNotice);
    assert.equal(
      replyNotice.target,
      `/movie/42?phimSlug=test-season#comment-${root.id}`
    );
    assert.equal(replyNotice.data.actorName, 'bob');
    assert.equal(await Notification.countDocuments({ recipient: bob._id }), 0);
    assert.equal(
      (
        await request('/api/comments', alice, 'POST', {
          movie: 42,
          text: 'Replying to myself should not notify',
          parentComment: root.id,
        })
      ).status,
      201
    );
    assert.equal(
      await Notification.countDocuments({ type: 'COMMENT_REPLY' }),
      1
    );
    const reply = await Comment.findById(posted.body.data._id);
    reply.text = 'Edited after posting';
    await reply.save();
    assert.equal(
      await Notification.countDocuments({ type: 'COMMENT_REPLY' }),
      1
    );
    assert.equal(
      (
        await request('/api/comments', bob, 'POST', {
          movie: 99,
          text: 'Wrong movie parent reference',
          parentComment: root.id,
        })
      ).status,
      404
    );

    const held = await Comment.create({
      user: bob._id,
      movie: 42,
      text: 'Held for moderation',
      parentComment: root._id,
      isApproved: false,
    });
    assert.equal(
      await Notification.countDocuments({ type: 'COMMENT_REPLY' }),
      1
    );
    assert.equal(
      (
        await request(`/api/admin/comments/${held.id}`, staff, 'PUT', {
          isApproved: true,
        })
      ).status,
      200
    );
    assert.equal(
      await Notification.countDocuments({ type: 'COMMENT_REPLY' }),
      2
    );
    const spoiler = await Comment.create({
      user: bob._id,
      movie: 42,
      text: 'A spoiler should not be in the preview',
      parentComment: root._id,
      isSpoiler: true,
    });
    assert.equal(
      (await Notification.findOne({ dedupeKey: `reply:${spoiler.id}` })).data
        .preview,
      ''
    );

    assert.equal(
      (await request(`/api/notifications/${replyNotice.id}`, bob)).status,
      404
    );
    assert.equal(
      (await request(`/api/notifications/${replyNotice.id}/read`, bob, 'PUT'))
        .status,
      404
    );
    assert.equal((await Notification.findById(replyNotice.id)).readAt, null);
    const controller = new AbortController();
    aborters.push(controller);
    const stream = await fetch(origin + '/api/notifications/events', {
      headers: { Authorization: `Bearer ${alice.getSignedJwtToken()}` },
      signal: controller.signal,
    });
    assert.equal(stream.status, 200);
    const reader = stream.body.getReader();
    const decoder = new TextDecoder();
    assert.match(decoder.decode((await reader.read()).value), /event: ready/);
    const otherEvents = [];
    const unsubscribe = notificationEvents.subscribe(bob.id, (event) =>
      otherEvents.push(event)
    );
    await createNotification({
      recipient: alice._id,
      type: 'COMMENT_REPLY',
      dedupeKey: 'live-created',
      target: '/profile',
      data: {},
    });
    assert.match(
      decoder.decode((await reader.read()).value),
      /"kind":"created"/
    );
    const marked = await request(
      `/api/notifications/${replyNotice.id}/read`,
      alice,
      'PUT'
    );
    assert.equal(marked.status, 200);
    const firstReadAt = marked.body.data.readAt;
    assert.match(decoder.decode((await reader.read()).value), /"kind":"read"/);
    assert.equal(otherEvents.length, 0);
    unsubscribe();
    controller.abort();
    assert.equal(
      (await request(`/api/notifications/${replyNotice.id}/read`, alice, 'PUT'))
        .body.data.readAt,
      firstReadAt
    );
    assert.equal(
      (await request('/api/notifications/read-all', bob, 'PUT')).status,
      200
    );
    assert.ok(
      (await request('/api/notifications/unread-count')).body.data.unreadCount >
        0
    );
    await request('/api/notifications/read-all', alice, 'PUT');
    assert.equal(
      (await request('/api/notifications/unread-count')).body.data.unreadCount,
      0
    );
    assert.equal(
      (await request('/api/notifications?unread=true')).body.data.length,
      0
    );

    const restriction = await request(
      `/api/admin/users/${alice.id}/comment-restriction`,
      staff,
      'PUT',
      { reason: 'Repeated spam comments', duration: '1h' }
    );
    assert.equal(restriction.status, 200);
    const restricted = await Notification.findOne({
      recipient: alice._id,
      type: 'COMMENT_RESTRICTED',
    });
    assert.equal(restricted.data.reason, 'Repeated spam comments');
    assert.ok(restricted.data.restrictionExpiresAt > new Date());
    await request(
      `/api/admin/users/${alice.id}/comment-restriction`,
      staff,
      'DELETE'
    );
    await request(
      `/api/admin/users/${alice.id}/comment-restriction`,
      staff,
      'DELETE'
    );
    assert.equal(
      await Notification.countDocuments({
        recipient: alice._id,
        type: 'COMMENT_RESTRICTION_LIFTED',
      }),
      1
    );

    const sent = await request('/api/reports', bob, 'POST', {
      type: 'MOVIE',
      targetId: 'phim:notification-demo',
      reason: 'PLAYBACK_ERROR',
      description: 'This source will not start playback.',
    });
    assert.equal(sent.status, 201);
    const reportId = sent.body.data._id;
    const adminNotice = await Notification.findOne({
      recipient: staff._id,
      type: 'ADMIN_REPORT',
    });
    assert.equal(adminNotice.target, `/admin/reports?report=${reportId}`);
    assert.equal(
      (
        await request(`/api/admin/reports/${reportId}/resolve`, staff, 'POST', {
          resolution:
            'Internal moderation details: do not expose to the reporter.',
        })
      ).status,
      200
    );
    const outcome = await Notification.findOne({
      recipient: bob._id,
      type: 'REPORT_RESOLVED',
    });
    assert.ok(outcome);
    const privateData = (await request(`/api/notifications/${outcome.id}`, bob))
      .body.data;
    assert.equal(privateData.dedupeKey, undefined);
    assert.equal(privateData.recipient, undefined);
    assert.equal(
      JSON.stringify(privateData).includes('Internal moderation'),
      false
    );
    const reports = await Report.insertMany(
      ['one', 'two'].map((slug) => ({
        reporter: alice._id,
        type: 'MOVIE',
        targetId: `phim:${slug}`,
        reason: 'OTHER',
        description: 'Bulk notification test report',
      }))
    );
    const bulk = await request(
      '/api/admin/reports/bulk-action',
      staff,
      'POST',
      {
        action: 'reject',
        reportIds: reports.map((report) => report.id),
        reason: 'Reviewed and not actionable.',
      }
    );
    assert.equal(bulk.body.modifiedCount, 2);
    assert.equal(
      await Notification.countDocuments({
        recipient: alice._id,
        type: 'REPORT_REJECTED',
      }),
      2
    );

    let delivered = 0;
    const unsub = notificationEvents.subscribe(alice.id, (event) => {
      if (event.kind === 'created') delivered++;
    });
    await Promise.all(
      Array.from({ length: 4 }, () =>
        createNotification({
          recipient: alice._id,
          type: 'COMMENT_REPLY',
          dedupeKey: 'race-test',
          target: '/profile',
          data: {},
        })
      )
    );
    assert.equal(
      await Notification.countDocuments({ dedupeKey: 'race-test' }),
      1
    );
    assert.equal(delivered, 1);
    unsub();
    await Notification.insertMany(
      Array.from({ length: 25 }, (_, index) => ({
        recipient: alice._id,
        type: 'COMMENT_REPLY',
        target: '/profile',
        dedupeKey: `page-${index}`,
        data: {},
      }))
    );
    const pageOne = (await request('/api/notifications')).body;
    const pageTwo = (await request('/api/notifications?page=2')).body;
    assert.equal(pageOne.data.length, 20);
    assert.ok(pageTwo.data.length > 0);
    assert.equal(
      pageOne.data.some((first) =>
        pageTwo.data.some((second) => first._id === second._id)
      ),
      false
    );
    const thread = await request(`/api/comments/${root.id}/thread`, null);
    assert.equal(thread.body.data._id, root.id);
    await Comment.updateOne({ _id: root._id }, { isHidden: true });
    assert.equal(
      (await request(`/api/comments/${root.id}/thread`, null)).status,
      404
    );
  }
);
